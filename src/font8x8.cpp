bool FontRenderer::init(SDL_Renderer* rend) {
    renderer = rend;
    if (font_atlas) {
        SDL_DestroyTexture(font_atlas);
        font_atlas = nullptr;
    }

    // Create an atlas containing all 95 characters horizontally: 95 * 8 = 760 width, 8 height
    const int atlas_w = 95 * 8;
    const int atlas_h = 8;
    std::vector<unsigned int> pixels(atlas_w * atlas_h, 0x00000000);

    for (int ch = 0; ch < 95; ++ch) {
        int char_x = ch * 8;
        for (int row = 0; row < 8; ++row) {
            unsigned char byte = FONT8X8_BASIC[ch][row];
            for (int col = 0; col < 8; ++col) {
                if (byte & (0x80 >> col)) {
                    pixels[row * atlas_w + (char_x + col)] = 0xFFFFFFFF; // White opaque
                }
            }
        }
    }

    font_atlas = SDL_CreateTexture(
        renderer,
        SDL_PIXELFORMAT_ARGB8888,
        SDL_TEXTUREACCESS_STATIC,
        atlas_w, atlas_h
    );

    if (!font_atlas) return false;

    SDL_SetTextureBlendMode(font_atlas, SDL_BLENDMODE_BLEND);
    SDL_UpdateTexture(font_atlas, nullptr, pixels.data(), atlas_w * sizeof(unsigned int));
    return true;
}

void FontRenderer::draw_text(const std::string& text, int x, int y, SDL_Color color, int scale) {
    if (!font_atlas || !renderer) return;

    SDL_SetTextureColorMod(font_atlas, color.r, color.g, color.b);
    SDL_SetTextureAlphaMod(font_atlas, color.a);

    int cur_x = x;
    int cur_y = y;

    for (char c : text) {
        if (c == '\n') {
            cur_x = x;
            cur_y += 10 * scale;
            continue;
        }

        if (c < 32 || c > 126) c = '?';

        int ch_idx = c - 32;
        SDL_Rect src_rect = { ch_idx * 8, 0, 8, 8 };
        SDL_Rect dst_rect = { cur_x, cur_y, 8 * scale, 8 * scale };

        SDL_RenderCopy(renderer, font_atlas, &src_rect, &dst_rect);
        cur_x += 8 * scale;
    }
}

void FontRenderer::draw_text_centered(const std::string& text, int center_x, int y, SDL_Color color, int scale) {
    int w = get_text_width(text, scale);
    draw_text(text, center_x - w / 2, y, color, scale);
}

int FontRenderer::get_text_width(const std::string& text, int scale) const {
    int max_len = 0;
    int cur_len = 0;
    for (char c : text) {
        if (c == '\n') {
            if (cur_len > max_len) max_len = cur_len;
            cur_len = 0;
        } else {
            cur_len++;
        }
    }
    if (cur_len > max_len) max_len = cur_len;
    return max_len * 8 * scale;
}

int FontRenderer::get_text_height(int scale) const {
    return 8 * scale;
}
